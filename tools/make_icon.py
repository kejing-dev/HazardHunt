"""Hazard Hunt icon (design `appIcon`): one set of shapes drawn three ways, so they always match:
the adaptive-icon foreground vector (`res/drawable/ic_launcher_foreground.xml`), the legacy launcher PNG and the
512 export for the factory gallery.

    python tools/make_icon.py <export-512.png>

Industrial blue-grey tile #2F4858 (the factory's only one), a white flat magnifier (ring + short handle) framing a
small hazard-orange pennant flag, and a thin yellow / black hazard-stripe band along the bottom. No text, no
gradient. Coordinates are the vector's 108-unit viewport (safe zone 21..87).
"""
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
TILE = (0x2F, 0x48, 0x58, 255)
WHITE = (255, 255, 255, 255)
ORANGE = (0xFF, 0x7A, 0x1A, 255)
YELLOW = (0xF5, 0xC4, 0x00, 255)
BLACK = (0x1F, 0x1F, 0x1F, 255)

RING = (47.0, 45.0, 15.5, 5.0)  # centre x, y, radius, stroke
HANDLE = ((58.6, 56.6), (70.5, 68.5), 7.0)
POLE = ((41.0, 55.0), (41.0, 35.0), 2.6)
PENNANT = [(42.2, 35.2), (56.0, 40.2), (42.2, 45.2)]
BAND = (27.0, 76.0, 81.0, 82.0)  # x0, y0, x1, y1
STRIPE = 4.0  # stripe width along x
SKEW = 6.0  # x shift from the band's bottom to its top


def clip(poly, x0, y0, x1, y1):
    """Sutherland-Hodgman: polygon clipped to the axis-aligned rectangle."""

    def cut(pts, inside, inter):
        out = []
        for i in range(len(pts)):
            a = pts[i - 1]
            b = pts[i]
            if inside(b):
                if not inside(a):
                    out.append(inter(a, b))
                out.append(b)
            elif inside(a):
                out.append(inter(a, b))
        return out

    def ix(x):
        return lambda a, b: (x, a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]))

    def iy(y):
        return lambda a, b: (a[0] + (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]), y)

    pts = poly
    for inside, inter in (
        (lambda p: p[0] >= x0, ix(x0)),
        (lambda p: p[0] <= x1, ix(x1)),
        (lambda p: p[1] >= y0, iy(y0)),
        (lambda p: p[1] <= y1, iy(y1)),
    ):
        pts = cut(pts, inside, inter)
        if not pts:
            break
    return pts


def stripes():
    x0, y0, x1, y1 = BAND
    out = []
    x = x0 - SKEW - STRIPE
    while x < x1 + SKEW:
        quad = [(x, y1), (x + STRIPE, y1), (x + STRIPE + SKEW, y0), (x + SKEW, y0)]
        c = clip(quad, x0, y0, x1, y1)
        if len(c) >= 3:
            out.append(c)
        x += 2 * STRIPE
    return out


def path(pts):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "z"


def vector():
    def stroke(d, w):
        return (
            "    <path\n"
            f'        android:pathData="{d}"\n'
            '        android:strokeColor="#FFFFFFFF"\n'
            f'        android:strokeWidth="{w}"\n'
            '        android:strokeLineCap="round"\n'
            '        android:strokeLineJoin="round"\n'
            '        android:fillColor="#00000000" />\n'
        )

    def fill(d, color):
        return f'    <path\n        android:pathData="{d}"\n        android:fillColor="{color}" />\n'

    cx, cy, r, w = RING
    (hx0, hy0), (hx1, hy1), hw = HANDLE
    (px0, py0), (px1, py1), pw = POLE
    x0, y0, x1, y1 = BAND
    out = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- Hazard Hunt: white magnifier framing an orange pennant, hazard-stripe band (design appIcon); "
        "generated by tools/make_icon.py -->\n",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n',
        stroke(f"M{cx - r},{cy}a{r},{r} 0,1 1,{2 * r},0a{r},{r} 0,1 1,{-2 * r},0z", w),
        stroke(f"M{hx0},{hy0} L{hx1},{hy1}", hw),
        stroke(f"M{px0},{py0} L{px1},{py1}", pw),
        fill(path(PENNANT), "#FFFF7A1A"),
        fill(path([(x0, y0), (x1, y0), (x1, y1), (x0, y1)]), "#FFF5C400"),
    ]
    for s in stripes():
        out.append(fill(path(s), "#FF1F1F1F"))
    out.append("</vector>\n")
    return "".join(out)


def draw(size, rounded):
    S = 1080
    K = S / 108.0
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if rounded:
        d.rounded_rectangle((0, 0, S, S), radius=int(S * 0.22), fill=TILE)
    else:
        d.rectangle((0, 0, S, S), fill=TILE)

    def dot(x, y, rr, color=WHITE):
        d.ellipse(((x - rr) * K, (y - rr) * K, (x + rr) * K, (y + rr) * K), fill=color)

    cx, cy, r, w = RING
    d.ellipse(((cx - r - w / 2) * K, (cy - r - w / 2) * K, (cx + r + w / 2) * K, (cy + r + w / 2) * K), outline=WHITE, width=int(w * K))
    (hx0, hy0), (hx1, hy1), hw = HANDLE
    d.line([(hx0 * K, hy0 * K), (hx1 * K, hy1 * K)], fill=WHITE, width=int(hw * K))
    dot(hx0, hy0, hw / 2)
    dot(hx1, hy1, hw / 2)
    (px0, py0), (px1, py1), pw = POLE
    d.line([(px0 * K, py0 * K), (px1 * K, py1 * K)], fill=WHITE, width=int(pw * K))
    dot(px0, py0, pw / 2)
    dot(px1, py1, pw / 2)
    d.polygon([(x * K, y * K) for x, y in PENNANT], fill=ORANGE)
    x0, y0, x1, y1 = BAND
    d.rectangle((x0 * K, y0 * K, x1 * K, y1 * K), fill=YELLOW)
    for s in stripes():
        d.polygon([(x * K, y * K) for x, y in s], fill=BLACK)
    return im.resize((size, size), Image.LANCZOS)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "icon-512.png")
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf8", newline="\n") as f:
        f.write(vector())
    os.makedirs(os.path.join(RES, "mipmap-xxxhdpi"), exist_ok=True)
    draw(512, rounded=True).save(out)
    draw(192, rounded=False).save(os.path.join(RES, "mipmap-xxxhdpi", "ic_launcher.png"))
    print("wrote", out)


if __name__ == "__main__":
    main()
